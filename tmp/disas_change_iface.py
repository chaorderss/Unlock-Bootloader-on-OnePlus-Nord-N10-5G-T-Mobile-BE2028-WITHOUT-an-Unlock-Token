    s = f"+{off:03x}: {insn:08x}  "

    if insn == 0xd65f03c0:
        s += "ret"
    elif (insn >> 26) == 0x25:  # BL
        imm = insn & 0x3ffffff
        if imm & 0x2000000: imm -= 0x4000000
        s += f"bl +{off + imm * 4:#x}"
    elif (insn >> 24) == 0x71:  # CMP
        rn = (insn >> 5) & 0x1f
        imm = (insn >> 10) & 0xfff
